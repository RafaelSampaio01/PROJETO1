# ============================================================
# MAIN LOOP — MENU PRINCIPAL
# ============================================================

oled.init()
draw(cursor)

while True:
    key = read_menu()
    now = ticks_ms()

    if key:
        last_input_time = now
        text_scroll_x = 0

        if key == "LEFT":
            old = cursor
            cursor = (cursor - 1) % len(MENU)
            shift_left(MENU[old], MENU[cursor])

        elif key == "RIGHT":
            old = cursor
            cursor = (cursor + 1) % len(MENU)
            shift_right(MENU[old], MENU[cursor])

        # ===============================
        # OK → entra na tela
        # ===============================
        elif key == "OK":
            fn = MENU[cursor].get("ok", None)
            if fn:
                oled.clear()
                oled.show()

                fn()   # ⬅️ AQUI A LISTA ASSUME O CONTROLE

                # ⬅️ SÓ EXECUTA QUANDO show() DER RETURN
                oled.init()
                draw(cursor)

    else:
        if ticks_diff(now, last_input_time) > IDLE_TIME:
            update_text_scroll(MENU[cursor])

    draw(cursor, text_scroll_x)
    sleep_ms(20)

