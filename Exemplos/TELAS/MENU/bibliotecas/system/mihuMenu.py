TEXT_AREA_WIDTH = 88
CHAR_WIDTH = 8
SCROLL_SPEED = 1
SCROLL_DELAY = 40
IDLE_TIME = 800

# ============================================================
# ESTADO
# ============================================================

cursor = 0
text_scroll_x = 0
last_input_time = ticks_ms()
last_scroll_time = ticks_ms()

# ============================================================
# RENDER
# ============================================================

def render_item(item, dx=0, text_dx=0):
    # item["icon"] é FrameBuffer, então draw_icon funciona na sua lib,
    # mas se sua lib tiver "blit", pode usar também.
    oled.draw_icon(item["icon"], item["x"] + dx, item["y"])
    oled.text(item["label"], item["tx"] + dx + text_dx, item["ty"])

def draw(idx, text_dx=0):
    oled.clear()
    render_item(MENU[idx], text_dx=text_dx)
    oled.show()

# ============================================================
# SHIFT
# ============================================================

def shift_left(old_item, new_item):
    global text_scroll_x
    text_scroll_x = 0

    for i in range(17):
        dx = int(128 / 16 * i)
        oled.clear()
        render_item(old_item, dx=-dx)
        render_item(new_item, dx=128 - dx)
        oled.show()
        sleep_ms(10)

def shift_right(old_item, new_item):
    global text_scroll_x
    text_scroll_x = 0

    for i in range(17):
        dx = int(128 / 16 * i)
        oled.clear()
        render_item(old_item, dx=dx)
        render_item(new_item, dx=-128 + dx)
        oled.show()
        sleep_ms(10)

# ============================================================
# TEXTO COM SCROLL AUTOMÁTICO
# ============================================================

def update_text_scroll(item):
    global text_scroll_x, last_scroll_time

    label_width = len(item["label"]) * CHAR_WIDTH
    overflow = label_width - TEXT_AREA_WIDTH

    if overflow <= 0:
        text_scroll_x = 0
        return

    now = ticks_ms()
    if ticks_diff(now, last_scroll_time) > SCROLL_DELAY:
        text_scroll_x -= SCROLL_SPEED
        if abs(text_scroll_x) > overflow:
            text_scroll_x = 0
        last_scroll_time = now

